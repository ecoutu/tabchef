// Precompiles the config JSON schema into a standalone validator (no eval / new Function at runtime,
// required by MV3 CSP). Usage: node scripts/gen-validator.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = new URL('../', import.meta.url);
const schemaPath = new URL('src/core/config/config.schema.json', root);
export const outPath = new URL('src/core/config/validate-config.generated.js', root);

export function generate() {
  const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
  const ajv = new Ajv({ allErrors: true, unicode: false, code: { source: true, esm: true } });
  const validate = ajv.compile(schema);
  return '// @generated by scripts/gen-validator.mjs from config.schema.json. Do not edit.\n' + standaloneCode(ajv, validate);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outPath, generate());
  console.log('wrote', fileURLToPath(outPath));
}
